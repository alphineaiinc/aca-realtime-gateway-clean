'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { Pool } = require('pg');
const { createStripeEventReceiptStore } = require('../src/security/stripeEventReceipt');
test('durable receipt claims survive independent pools and block uncertain resend', {skip: process.env.RUN_STRIPE_RECEIPT_CI !== '1'}, async t => {
  const url = process.env.STRIPE_RECEIPT_CI_URL;
  const parsed = new URL(url);
  assert.equal(parsed.hostname, '127.0.0.1');
  assert.equal(parsed.pathname, '/aca_stripe_ci');
  const pools = [new Pool({connectionString:url}), new Pool({connectionString:url})];
  t.after(async()=>Promise.all(pools.map(p=>p.end())));
  await pools[0].query(require('node:fs').readFileSync('migrations/draft_stripe_event_receipts.sql','utf8'));
  const stores = pools.map(createStripeEventReceiptStore);
  const id = 'evt_' + require('node:crypto').randomUUID().replaceAll('-','');
  const results = await Promise.all(Array.from({length:20},(_,i)=>stores[i%2].claim(id)));
  assert.equal(results.filter(r=>r.status==='claimed').length,1);
  assert.equal(results.filter(r=>r.status==='blocked').length,19);
  const claim = results.find(r=>r.status==='claimed');
  await assert.rejects(stores[1].finish(id,require('node:crypto').randomUUID(),'completed'));
  await stores[0].finish(id,claim.claimId,'completed');
  assert.equal((await stores[1].claim(id)).status,'completed');
  const other = id + '_uncertain';
  const pending = await stores[1].claim(other);
  await stores[1].finish(other,pending.claimId,'uncertain');
  assert.equal((await stores[0].claim(other)).status,'blocked');
  const unresolved = await stores[0].listUnresolved(100);
  assert.ok(unresolved.some(row=>row.event_id===other && row.state==='uncertain'));
  assert.ok(!unresolved.some(row=>row.event_id===id));
  assert.ok(unresolved.every(row=>!Object.hasOwn(row,'claim_id')));
  await assert.rejects(stores[0].listUnresolved(501));
});
