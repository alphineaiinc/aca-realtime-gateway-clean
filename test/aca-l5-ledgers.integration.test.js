const test=require('node:test');
const assert=require('node:assert/strict');
const {Pool}=require('pg');
const fs=require('node:fs');
const {createVerifiedUsageStore}=require('../src/security/verifiedUsage');
const {createBillingPeriodClosure}=require('../src/security/billingPeriodClosure');
const {createPartnerReservation}=require('../src/security/partnerReservation');
test('commercial ledgers serialize closure and reservations',{skip:process.env.RUN_STRIPE_RECEIPT_CI!=='1'},async t=>{
 const url=process.env.STRIPE_RECEIPT_CI_URL;
 const parsed=new URL(url);assert.equal(parsed.hostname,'127.0.0.1');assert.equal(parsed.pathname,'/aca_stripe_ci');
 const admin=new Pool({connectionString:url});
 const schema='aca_ledger_'+require('node:crypto').randomBytes(8).toString('hex');
 await admin.query('CREATE SCHEMA '+schema);
 const pool=new Pool({connectionString:url,options:'-c search_path='+schema});
 t.after(async()=>{await pool.end();await admin.query('DROP SCHEMA '+schema+' CASCADE');await admin.end();});
 await pool.query('CREATE TABLE master_tenants(id integer PRIMARY KEY); CREATE TABLE partners(id integer PRIMARY KEY); CREATE TABLE billing_invoices(id serial PRIMARY KEY,tenant_id integer,amount_usd numeric(10,2),period_start timestamp,period_end timestamp,status text); INSERT INTO master_tenants VALUES(1),(2); INSERT INTO partners VALUES(1),(2)');
 for(const file of ['draft_aca_verified_usage.sql','draft_aca_partner_reservations.sql'])await pool.query(fs.readFileSync('migrations/'+file,'utf8'));
 await pool.query("INSERT INTO aca_billing_prices VALUES('v1','call_second',10000); INSERT INTO aca_partner_funds VALUES(1,1000),(2,1000)");
 const record=createVerifiedUsageStore(pool);
 const f={source:'twilio',sourceId:'CAfixture',unit:'call_second',tenantId:1,quantity:60,priceVersion:'v1',occurredAt:'2020-01-01T00:00:00Z'};
 assert.equal(await record(f),'recorded');assert.equal(await record(f),'duplicate');
 await assert.rejects(record({...f,tenantId:2}));
 await assert.rejects(pool.query("UPDATE aca_billing_prices SET micro_usd_per_unit=1"));
 const close=createBillingPeriodClosure(pool);
 const results=await Promise.all(Array.from({length:8},()=>close(1,'2020-01-01')));
 assert.ok(results.every(x=>x.invoice_id===results[0].invoice_id&&String(x.amount_cents)==='60'));
 assert.equal((await pool.query('SELECT count(*) FROM billing_invoices')).rows[0].count,'1');
 await assert.rejects(record({...f,sourceId:'CAlate'}));
 assert.equal((await close(2,'2020-01-01')).invoice_id,null);
 const reserve=createPartnerReservation(pool);
 const outcomes=await Promise.allSettled(Array.from({length:8},(_,i)=>reserve(1,'fixture_request_'+i,300)));
 assert.equal(outcomes.filter(x=>x.status==='fulfilled').length,3);
 assert.equal((await pool.query('SELECT available_cents FROM aca_partner_funds WHERE partner_id=1')).rows[0].available_cents,'100');
 assert.equal((await pool.query('SELECT available_cents FROM aca_partner_funds WHERE partner_id=2')).rows[0].available_cents,'1000');
 const winner=outcomes.findIndex(x=>x.status==='fulfilled');
 assert.equal(await reserve(1,'fixture_request_'+winner,300),'duplicate');
});
