"use strict";
const test=require("node:test"),assert=require("node:assert/strict"),fs=require("node:fs");
const {Pool}=require("pg");
const {recordUsage}=require("../src/analytics/billableUsage");
const {invoiceClosedMonth}=require("../src/brain/closedMonthInvoice");
test("isolated commercial pricing, replay and concurrent invoice acceptance",async()=>{
 const pool=new Pool({connectionString:"postgres://onboarding_test:onboarding_test_only@127.0.0.1:5432/aca_commercial_ci",options:"-c timezone=UTC"});
 try{
 await pool.query("CREATE TABLE public.master_tenants(id integer PRIMARY KEY); INSERT INTO public.master_tenants VALUES(1),(2); CREATE TABLE public.analytics_events(id bigserial PRIMARY KEY,tenant_id integer,event_type text,quantity numeric,unit text,meta jsonb,created_at timestamp DEFAULT NOW()); CREATE TABLE public.billing_invoices(id serial PRIMARY KEY,tenant_id integer,usage_minutes numeric,ai_tokens integer,amount_usd numeric,status text,period_start timestamp,period_end timestamp)");
 for(const name of ["016_billable_usage_keys.sql","017_invoice_periods.sql","draft_aca_usage_identity.sql","draft_aca_period_pricing.sql","draft_aca_usage_closure_guard.sql"])await pool.query(fs.readFileSync("migrations/"+name,"utf8"));
 const event={tenantId:1,eventId:"CA_fixture",kind:"voice_seconds",quantity:60};
 assert.deepEqual(await recordUsage(pool,event),{stored:true});
 assert.deepEqual(await recordUsage(pool,event),{stored:false});
 await assert.rejects(recordUsage(pool,{...event,tenantId:2}),/CONFLICTING_USAGE_EVIDENCE/);
 await assert.rejects(recordUsage(pool,{...event,quantity:61}),/CONFLICTING_USAGE_EVIDENCE/);
 await pool.query("UPDATE public.analytics_events SET created_at='2020-01-15'");
 await pool.query(fs.readFileSync("migrations/draft_aca_usage_immutability.sql","utf8"));
 await assert.rejects(pool.query("UPDATE public.analytics_events SET quantity=999"),/IMMUTABLE_VERIFIED_USAGE/);
 await assert.rejects(pool.query("DELETE FROM public.analytics_events"),/IMMUTABLE_VERIFIED_USAGE/);
 await assert.rejects(pool.query("DELETE FROM public.aca_billable_usage_keys"),/IMMUTABLE_USAGE_KEY/);
 await pool.query("INSERT INTO public.analytics_events(tenant_id,event_type,quantity) VALUES(1,'ordinary',1)");
 await assert.rejects(pool.query("UPDATE public.analytics_events SET event_type='ACA_VERIFIED_USAGE' WHERE event_type='ordinary'"),/IMMUTABLE_VERIFIED_USAGE/);
 await pool.query("DELETE FROM public.analytics_events WHERE event_type='ordinary'");
 const input={tenantId:1,year:2020,month:1,minuteRateCents:60,tokenRateMicros:500};
 assert.equal(await invoiceClosedMonth(pool,input),null);
 await pool.query("INSERT INTO public.aca_period_pricing VALUES(1,'2020-01-01',60,500)");
 await assert.rejects(pool.query("UPDATE public.aca_period_pricing SET minute_rate_cents=1"),/IMMUTABLE_PERIOD_PRICE/);
 await assert.rejects(pool.query("DELETE FROM public.aca_period_pricing"),/IMMUTABLE_PERIOD_PRICE/);
 assert.equal(await invoiceClosedMonth(pool,{...input,minuteRateCents:61}),null);
 const results=await Promise.all(Array.from({length:12},()=>invoiceClosedMonth(pool,input)));
 assert.equal(results.filter(Boolean).length,1);
 assert.equal(Number(results.find(Boolean).amount_usd),0.6);
 assert.equal((await pool.query("SELECT count(*)::int AS n FROM public.billing_invoices")).rows[0].n,1);
 assert.equal(await invoiceClosedMonth(pool,{...input,tenantId:2}),null);
 await assert.rejects(pool.query("INSERT INTO public.analytics_events(tenant_id,event_type,quantity,unit,created_at) VALUES(1,'ACA_VERIFIED_USAGE',1,'voice_seconds','2020-01-20')"),/USAGE_PERIOD_CLOSED/);
 await pool.query(fs.readFileSync("migrations/draft_aca_usage_reconciliation.sql","utf8"));
 const {queueLateUsage}=require("../src/analytics/lateUsage");
 const late={tenantId:1,eventId:"CA_late",kind:"voice_seconds",quantity:15,occurredAt:new Date("2020-01-20T00:00:00Z")};
 const routed={...late,eventId:"CA_routed"};
 assert.deepEqual(await recordUsage(pool,routed),{stored:false,reconciliation:true,queued:true});
 assert.deepEqual(await recordUsage(pool,routed),{stored:false,reconciliation:true,queued:false});
 await assert.rejects(recordUsage(pool,{...routed,tenantId:2}),/CONFLICTING_USAGE_EVIDENCE/);
 await assert.rejects(queueLateUsage(pool,{...late,eventId:event.eventId}),/CONFLICTING_LATE_USAGE/);
 const queued=await Promise.all(Array.from({length:8},()=>queueLateUsage(pool,late)));
 assert.equal(queued.filter(x=>x.queued).length,1);
 await assert.rejects(queueLateUsage(pool,{...late,tenantId:2}),/CONFLICTING_LATE_USAGE/);
 await assert.rejects(queueLateUsage(pool,{...late,quantity:16}),/CONFLICTING_LATE_USAGE/);
 assert.equal((await pool.query("SELECT count(*)::int AS n FROM public.billing_invoices")).rows[0].n,1);
 await pool.query("CREATE TABLE public.aca_stripe_event_inbox(event_id text PRIMARY KEY)");
 await pool.query(fs.readFileSync("migrations/014_stripe_invoice_reconciliation.sql","utf8"));
 await pool.query(fs.readFileSync("migrations/draft_aca_stripe_customer_identity.sql","utf8"));
 const {bindInvoice}=require("../src/brain/stripeInvoiceBinding");
 const binding={invoiceId:results.find(Boolean).id,tenantId:1,stripeInvoiceId:"in_fixture",stripeCustomerId:"cus_fixture",amountCents:60,livemode:true};
 await assert.rejects(bindInvoice(pool,binding),/BINDING_REJECTED/);
 await pool.query("INSERT INTO public.aca_stripe_customer_identity VALUES(2,'cus_other',true),(1,'cus_fixture',true)");
 await assert.rejects(bindInvoice(pool,{...binding,stripeCustomerId:"cus_other"}),/BINDING_REJECTED/);
 await assert.rejects(bindInvoice(pool,{...binding,livemode:false}),/BINDING_REJECTED/);
 assert.equal((await bindInvoice(pool,binding)).invoice_id,binding.invoiceId);
 await assert.rejects(pool.query("INSERT INTO public.aca_stripe_customer_identity VALUES(2,'cus_fixture',true)"));
 await pool.query(fs.readFileSync("migrations/draft_aca_financial_roles.sql","utf8"));
 const client=await pool.connect();
 try{
 await client.query("SET ROLE aca_financial_meter");
 await assert.rejects(client.query("INSERT INTO public.aca_period_pricing VALUES(2,'2020-01-01',60,500)"),/permission denied/);
 await assert.rejects(client.query("TRUNCATE public.analytics_events"),/permission denied/);
 await assert.rejects(client.query("UPDATE public.analytics_events SET quantity=999"),/permission denied/);
 await client.query("RESET ROLE");
 await client.query("SET ROLE aca_financial_pricer");
 await client.query("INSERT INTO public.aca_period_pricing VALUES(2,'2020-01-01',60,500)");
 await assert.rejects(client.query("INSERT INTO public.aca_billable_usage_keys VALUES(2,'forbidden','voice_seconds')"),/permission denied/);
 await client.query("RESET ROLE");
 await client.query("SET ROLE aca_financial_closer");
 await assert.rejects(client.query("UPDATE public.aca_period_pricing SET minute_rate_cents=1"),/permission denied/);
 await assert.rejects(client.query("DELETE FROM public.billing_invoices"),/permission denied/);
 }finally{await client.query("RESET ROLE");client.release();}
 }finally{await pool.end();}
});
